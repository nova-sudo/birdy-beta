export const BADGE_STATE_KEYS = Object.keys(BADGE_STATES)

export function isBadgeStateKey(value) {
  return Object.hasOwn(BADGE_STATES, value)
}

/** The state a raw status word stands for ("In Stock", "in-stock" and "IN_STOCK" are one state). */
export function badgeStateOf(value) {
  const key = String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/[\s-]+/g, "_")
  return isBadgeStateKey(key) ? key : "unknown"
}
